#!/usr/bin/env bash
# step7-script.sh - autonomous in-guest game-blob bring-up + verifier for
# Step 7 (Game Blob Distribution), fetched at boot via archiso's automated-script
# hook (partyos-step7.ipxe passes script=<server>/boot/step7-script.sh). It runs
# on the tty1 root autologin once the live system is up, so it has full control
# and mirrors everything to the serial console the harness scrapes.
#
# What it does (Step 7):
#   1. CATALOG: fetch server/games/catalog.json from the server (the game list).
#   2. DOWNLOAD: for each game, download its compressed blob (a squashfs file).
#   3. MOUNT: mount the blob read-only (mount -t squashfs - the archiso kernel has
#      squashfs built in) and stack a writable tmpfs over it via OVERLAYFS so the
#      game lives at /home/gamer/games/<name> and can write savegames. This is the
#      overlayfs mount, kernel-only (no fuse userspace).
#   4. RUN: execute the game's entry script (bin/run.sh) as gamer from the mount;
#      capture its marker as proof the game ran FROM the mounted blob.
#   5. SIMULTANEOUS: do this for BOTH catalog games so two games are mounted and
#      runnable at the same time.
#
# Why a fetched script (not baked-in): the game logic iterates WITHOUT rebuilding
# the ~1.6GB squashfs; the image already ships curl + mount + the squashfs/overlay
# kernel modules used here.
#
# Markers (greppable on serial):
#   PARTYOS-STEP7-CATALOG-OK n=<count>     catalog fetched + parsed
#   PARTYOS-STEP7-BLOB-DOWNLOADED name=..  a blob downloaded (sha verified)
#   PARTYOS-STEP7-MOUNTED name=.. at=..    blob mounted via squashfs+overlay
#   PARTYOS-STEP7-GAME-RAN name=.. marker= the dummy game ran from its mount
#   PARTYOS-STEP7-MULTI-MOUNT n=<count>    >=2 games mounted simultaneously
#   PARTYOS-STEP7-READY                    all games mounted + ran - step passed
#   PARTYOS-STEP7-ALIVE                    heartbeats proving the system stays up
# HTTP callback (report_url injected by partyos-step7.ipxe, no hardcoded IP):
#   step=7 status=ok games=<n> mounted=<n> ran=<n> markers=<a,b>

SER=/dev/ttyS0; case "$(systemd-detect-virt 2>/dev/null)" in none|"") SER=/dev/null;; esac
say()  { echo "$*" > "${SER}" 2>/dev/null; echo "$*"; }

# server base + report base come from the kernel cmdline (no hardcoded IP).
report_base=""
for p in $(< /proc/cmdline); do case "$p" in
    report_url=*) report_base="${p#*=}";;
esac; done
# No report_url=: fail loudly. The stage still runs; only the reports are lost.
[ -n "${report_base}" ] || { m="PARTYOS-STEP7-NO-SERVER: no report_url= on /proc/cmdline"; echo "${m}" >&2; logger -t partyos -p user.err "${m}" 2>/dev/null || true; }
SERVER_BASE="${report_base}"   # same host serves the catalog + blobs

# resolve the desktop user: identity-setup renames the uid-1000 account
# gamer->USER_NAME and publishes the name to /run/partyos-username. NEVER hardcode
# 'gamer' - after a rename it does not exist.
USER_NAME="gamer"
[ -r /run/partyos-username ] && USER_NAME="$(tr -d '[:space:]' < /run/partyos-username)"
[ -n "${USER_NAME}" ] || USER_NAME="gamer"
HOME_DIR="/home/${USER_NAME}"

GAMES_DIR="${HOME_DIR}/games"
CACHE_DIR="/var/cache/partyos/games"          # downloaded blobs land here
MNT_BASE="/run/partyos-games"                 # read-only squashfs mountpoints
CATALOG_URL="${SERVER_BASE}/server/games/catalog.json"

say "PARTYOS-STEP7 boot script started (game blob distribution)"
say "PARTYOS-STEP7 user ${USER_NAME}: $(id "${USER_NAME}" 2>&1)"
say "PARTYOS-STEP7 server_base=${SERVER_BASE}"

install -d "${CACHE_DIR}" "${MNT_BASE}"
install -d -o "${USER_NAME}" -g "${USER_NAME}" "${GAMES_DIR}"

# --- ensure squashfs + overlay are available --------------------------------
# The archiso kernel ships both; modprobe is belt-and-braces (built-in returns 0).
modprobe squashfs 2>/dev/null || true
modprobe overlay  2>/dev/null || true
modprobe loop     2>/dev/null || true

# --- 1. fetch the catalog ----------------------------------------------------
CATALOG="/run/partyos-catalog.json"
say "PARTYOS-STEP7 fetching catalog ${CATALOG_URL}"
if ! curl -fsS --max-time 30 -o "${CATALOG}" "${CATALOG_URL}"; then
    say "PARTYOS-STEP7 ERROR catalog fetch failed"
    curl -s --max-time 5 "${report_base}/report?step=7&status=fail&reason=catalog" >/dev/null 2>&1 || true
    exit 1
fi

# Parse the catalog WITHOUT jq (not in the base image): pull each game's fields
# with grep/sed. The catalog is generated by us with one field per line, so a
# line-oriented parse is reliable. Collect parallel arrays.
mapfile -t NAMES   < <(grep -oE '"name":[[:space:]]*"[^"]*"'   "${CATALOG}" | sed -E 's/.*"name":[[:space:]]*"([^"]*)".*/\1/')
mapfile -t BLOBS   < <(grep -oE '"blob":[[:space:]]*"[^"]*"'   "${CATALOG}" | sed -E 's/.*"blob":[[:space:]]*"([^"]*)".*/\1/')
mapfile -t ENTRIES < <(grep -oE '"entry":[[:space:]]*"[^"]*"'  "${CATALOG}" | sed -E 's/.*"entry":[[:space:]]*"([^"]*)".*/\1/')
mapfile -t MARKERS < <(grep -oE '"marker":[[:space:]]*"[^"]*"' "${CATALOG}" | sed -E 's/.*"marker":[[:space:]]*"([^"]*)".*/\1/')
mapfile -t SHAS    < <(grep -oE '"sha256":[[:space:]]*"[^"]*"' "${CATALOG}" | sed -E 's/.*"sha256":[[:space:]]*"([^"]*)".*/\1/')

NGAMES="${#NAMES[@]}"
say "PARTYOS-STEP7-CATALOG-OK n=${NGAMES} games=$(IFS=,; echo "${NAMES[*]}")"
if [ "${NGAMES}" -lt 1 ]; then
    say "PARTYOS-STEP7 ERROR empty catalog"
    curl -s --max-time 5 "${report_base}/report?step=7&status=fail&reason=empty-catalog" >/dev/null 2>&1 || true
    exit 1
fi

# --- helper: download + verify + mount one game -----------------------------
# Returns 0 and leaves the game mounted at ${GAMES_DIR}/<name> on success.
mount_game() {
    local name="$1" blobpath="$2" sha="$3"
    local url="${SERVER_BASE}/${blobpath}"
    local blob="${CACHE_DIR}/${name}.squashfs"
    local lower="${MNT_BASE}/${name}"          # ro squashfs mount
    local scratch="${MNT_BASE}/${name}.rw"     # ONE tmpfs holding upper + work
    local dest="${GAMES_DIR}/${name}"          # final overlay mount (writable)

    # download
    say "PARTYOS-STEP7 downloading ${name} <- ${url}"
    if ! curl -fsS --max-time 60 -o "${blob}" "${url}"; then
        say "PARTYOS-STEP7 ERROR download ${name} failed"; return 1
    fi
    # integrity check (best-effort; sha256sum is in coreutils)
    if [ -n "${sha}" ] && command -v sha256sum >/dev/null 2>&1; then
        local got; got="$(sha256sum "${blob}" | awk '{print $1}')"
        if [ "${got}" != "${sha}" ]; then
            say "PARTYOS-STEP7 ERROR ${name} sha mismatch got=${got} want=${sha}"; return 1
        fi
    fi
    say "PARTYOS-STEP7-BLOB-DOWNLOADED name=${name} bytes=$(wc -c < "${blob}" | tr -d ' ') sha_ok=1"

    # mount the squashfs read-only (lower layer)
    install -d "${lower}" "${scratch}"
    install -d -o "${USER_NAME}" -g "${USER_NAME}" "${dest}"
    if ! mountpoint -q "${lower}"; then
        if ! mount -t squashfs -o ro,loop "${blob}" "${lower}" 2>/dev/null; then
            # some kernels auto-loop; retry without explicit loop
            if ! mount -t squashfs -o ro "${blob}" "${lower}" 2>/dev/null; then
                say "PARTYOS-STEP7 ERROR squashfs mount ${name} failed"; return 1
            fi
        fi
    fi

    # ONE tmpfs holds BOTH the overlay upperdir and workdir. overlayfs requires
    # upperdir and workdir to reside on the SAME mount (otherwise: "workdir and
    # upperdir must reside under the same mount"), so they must share this tmpfs -
    # not two separate /run dirs.
    mountpoint -q "${scratch}" || mount -t tmpfs -o size=16M tmpfs "${scratch}" || true
    install -d "${scratch}/upper" "${scratch}/work"

    # overlay: ro squashfs lower + tmpfs upper -> writable game dir for gamer
    if ! mountpoint -q "${dest}"; then
        if ! mount -t overlay overlay \
              -o "lowerdir=${lower},upperdir=${scratch}/upper,workdir=${scratch}/work" \
              "${dest}" 2>/dev/null; then
            say "PARTYOS-STEP7 ERROR overlay mount ${name} failed"; return 1
        fi
    fi
    chown "${USER_NAME}:${USER_NAME}" "${dest}" 2>/dev/null || true
    say "PARTYOS-STEP7-MOUNTED name=${name} at=${dest} src=squashfs+overlay"
    return 0
}

# --- 2-3. download + mount every catalog game --------------------------------
declare -a MOUNTED=() RAN=() RAN_MARKERS=()
i=0
while [ "${i}" -lt "${NGAMES}" ]; do
    name="${NAMES[$i]}"; blob="${BLOBS[$i]}"; entry="${ENTRIES[$i]:-bin/run.sh}"
    marker="${MARKERS[$i]:-}"; sha="${SHAS[$i]:-}"
    i=$((i+1))
    if mount_game "${name}" "${blob}" "${sha}"; then
        MOUNTED+=("${name}")
        # --- 4. RUN the game from its mounted blob (as gamer) ----------------
        dest="${GAMES_DIR}/${name}"
        out=""
        if [ -x "${dest}/${entry}" ] || [ -f "${dest}/${entry}" ]; then
            out="$(sudo -u "${USER_NAME}" bash "${dest}/${entry}" 2>&1 || true)"
        else
            out="(no entry ${entry} in ${name})"
        fi
        say "PARTYOS-STEP7 game ${name} output: ${out}"
        if [ -n "${marker}" ] && echo "${out}" | grep -qF "${marker}"; then
            RAN+=("${name}"); RAN_MARKERS+=("${marker}")
            say "PARTYOS-STEP7-GAME-RAN name=${name} marker=${marker}"
            # prove the overlay upper is writable: the game wrote a savegame
            if [ -f "${dest}/savegame.dat" ]; then
                say "PARTYOS-STEP7 savegame written name=${name} (overlay upper writable)"
            fi
        else
            say "PARTYOS-STEP7 WARN game ${name} did not emit expected marker"
        fi
    fi
done

NMOUNTED="${#MOUNTED[@]}"
NRAN="${#RAN[@]}"
say "PARTYOS-STEP7 summary mounted=${NMOUNTED}/${NGAMES} ran=${NRAN}/${NGAMES}"

# --- 5. simultaneous-mount proof --------------------------------------------
# Count how many of our game dirs are CURRENTLY overlay mounts at the same time.
live=0
for n in "${MOUNTED[@]:-}"; do
    [ -z "${n}" ] && continue
    if mountpoint -q "${GAMES_DIR}/${n}"; then live=$((live+1)); fi
done
say "PARTYOS-STEP7 live simultaneous mounts: ${live}"
if [ "${live}" -ge 2 ]; then
    say "PARTYOS-STEP7-MULTI-MOUNT n=${live} (>=2 games mounted simultaneously)"
fi
say "PARTYOS-STEP7 mount table (games):"
mount | grep -F "${GAMES_DIR}/" > "${SER}" 2>/dev/null || true

# --- ready + callback --------------------------------------------------------
markers_csv="$(IFS=,; echo "${RAN_MARKERS[*]:-}")"
ready=0
if [ "${NMOUNTED}" -ge 2 ] && [ "${NRAN}" -ge 2 ] && [ "${live}" -ge 2 ]; then
    ready=1
    say "PARTYOS-STEP7-READY all games downloaded, mounted (overlay) and ran; ${live} simultaneous"
    curl -s --max-time 5 \
      "${report_base}/report?step=7&status=ok&games=${NGAMES}&mounted=${NMOUNTED}&ran=${NRAN}&simultaneous=${live}&markers=${markers_csv}" \
      >/dev/null 2>&1 || say "PARTYOS-STEP7 callback-failed (non-fatal)"
else
    say "PARTYOS-STEP7 NOT ready (mounted=${NMOUNTED} ran=${NRAN} live=${live})"
    curl -s --max-time 5 \
      "${report_base}/report?step=7&status=fail&games=${NGAMES}&mounted=${NMOUNTED}&ran=${NRAN}&simultaneous=${live}" \
      >/dev/null 2>&1 || true
fi

# --- heartbeats: prove the system stays up with games mounted ----------------
i=0
while [ "${i}" -lt 20 ]; do
    sleep 2; i=$((i+1))
    live_now=0
    for n in "${MOUNTED[@]:-}"; do
        [ -z "${n}" ] && continue
        mountpoint -q "${GAMES_DIR}/${n}" && live_now=$((live_now+1))
    done
    say "PARTYOS-STEP7-ALIVE heartbeat ${i} mounted=${live_now} ready=${ready}"
    [ "${ready}" -eq 1 ] && [ "${i}" -ge 6 ] && break
done

say "PARTYOS-STEP7 stay-up window complete, powering off"
systemctl poweroff --no-block 2>/dev/null || poweroff -f 2>/dev/null || true
