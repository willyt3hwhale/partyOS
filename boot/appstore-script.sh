#!/usr/bin/env bash
# appstore-script.sh - autonomous in-guest verifier for the App Store / Launcher,
# fetched at boot via archiso's automated-script hook (partyos-appstore.ipxe passes
# script=<server>/boot/appstore-script.sh). Runs on the tty1 root autologin once
# the live system is up, mirroring to the serial console the harness scrapes.
#
# The LOGIC under test is BAKED into the custom image (build-custom-image.sh):
#   /usr/local/bin/partyos-app        the app-store BACKEND (CLI)
#   gen-launchers -> per-app menu + desktop (category-subdir) icons = the store
# There is no store WINDOW: the auto-generated install-on-click icons ARE the
# store. The test drives the CLI backend, not GUI clicks: a
# real click and this headless run share the exact same partyos-app code path.
#
# What it proves:
#   1. partyos-app list shows the LAN catalog (>=1 app; the dummy present).
#   2. install <dummy> on a not-yet-local blob DOWNLOADS it (cache MISS) and MOUNTS
#      it via squashfs+overlay - the dummy was NOT in the cache, so this is the
#      auto-download-if-absent path.
#   3. launch <dummy> RUNS it from the mounted blob (its game marker fires; a
#      callback carries the marker).
#   4. installed REFLECTS state: the dummy is listed after install, gone after remove.
#   5. install-launch <hello> (the one-click GUI path) auto-downloads+mounts+runs.
#   6. the LAUNCHER + .desktop entries are PRESENT (App Store .desktop baked +
#      per-blob shortcuts generated by gen-launchers).
#
# Markers (greppable on serial):
#   PARTYOS-APPSTORE-LIST-OK n=<count>            partyos-app list returned the catalog
#   PARTYOS-APP-CACHE-MISS / -DOWNLOADED / -INSTALLED / -LAUNCHED / -REMOVED / ...
#   PARTYOS-APPSTORE-INSTALLED-AFTER apps=<csv>   installed list AFTER install
#   PARTYOS-APPSTORE-INSTALLED-AFTER-REMOVE apps=<csv>
#   PARTYOS-APPSTORE-DESKTOP-OK store=<0|1> shortcuts=<n>
#   PARTYOS-APPSTORE-READY                        all assertions met - step passed
#   PARTYOS-APPSTORE-ALIVE                        heartbeats proving the system stays up
# HTTP callback (report_url injected by the ipxe, no hardcoded IP):
#   step=appstore status=ok list=<n> dummy_install=<0|1> dummy_run=<0|1>
#     dummy_marker=<m> installed_after=<csv> removed=<0|1> oneclick_run=<0|1>
#     store_desktop=<0|1> shortcuts=<n>

SER=/dev/ttyS0; case "$(systemd-detect-virt 2>/dev/null)" in none|"") SER=/dev/null;; esac
say()  { echo "$*" > "${SER}" 2>/dev/null; echo "$*"; }

report_base=""
for p in $(< /proc/cmdline); do case "$p" in
    report_url=*) report_base="${p#*=}";;
esac; done
# No report_url=: fail loudly. The stage still runs; only the reports are lost.
[ -n "${report_base}" ] || { m="PARTYOS-APPSTORE-NO-SERVER: no report_url= on /proc/cmdline"; echo "${m}" >&2; logger -t partyos -p user.err "${m}" 2>/dev/null || true; }
SERVER_BASE="${report_base}"
export PARTYOS_SERVER="${SERVER_BASE}"   # partyos-app reads the catalog from here

APP=/usr/local/bin/partyos-app
DUMMY="dummy"          # the not-yet-local blob to install (catalog id partyos.dummy)
DUMMY_MARK="PARTYOS-GAME-DUMMY-RAN"
ONECLICK="hello"       # the one-click install-launch app
ONECLICK_MARK="PARTYOS-GAME-HELLO-RAN"

say "PARTYOS-APPSTORE boot script started"
say "PARTYOS-APPSTORE server_base=${SERVER_BASE}"
say "PARTYOS-APPSTORE partyos-app present: $([ -x "${APP}" ] && echo yes || echo no)"

modprobe squashfs 2>/dev/null || true
modprobe overlay  2>/dev/null || true
modprobe loop     2>/dev/null || true

if [ ! -x "${APP}" ]; then
    say "PARTYOS-APPSTORE ERROR partyos-app backend missing"
    curl -s --max-time 5 "${report_base}/report?step=appstore&status=fail&reason=no-backend" >/dev/null 2>&1 || true
    exit 1
fi

# --- mount the USB stick rw so the cache is persistent (matches step8). If there
# is no stick, partyos-app falls back to the RAM cache - the install path still
# works; the test just exercises the USB-cache path when a stick is present. -----
LABEL="LANPARTY_HOME"; MNT="/mnt/usbhome"
udevadm settle 2>/dev/null || true
DEV="$(bash /usr/local/lib/partyos-usb-labels.sh resolve home 2>/dev/null || blkid -L "${LABEL}" 2>/dev/null || true)"
if [ -z "${DEV}" ]; then
    for _ in $(seq 1 15); do DEV="$(bash /usr/local/lib/partyos-usb-labels.sh resolve home 2>/dev/null || blkid -L "${LABEL}" 2>/dev/null || true)"; [ -n "${DEV}" ] && break; sleep 1; udevadm settle 2>/dev/null || true; done
fi
if [ -n "${DEV}" ]; then
    install -d "${MNT}"
    mountpoint -q "${MNT}" || mount -o rw "${DEV}" "${MNT}" 2>/dev/null || mount "${DEV}" "${MNT}" 2>/dev/null || true
    mount -o remount,rw "${MNT}" 2>/dev/null || true
    say "PARTYOS-APPSTORE usb mounted dev=${DEV} (cache persists on USB)"
else
    say "PARTYOS-APPSTORE no LANPARTY_HOME stick - using RAM cache"
fi

# ============================ 1. list ========================================
say "PARTYOS-APPSTORE === partyos-app list ==="
LIST_OUT="$(${APP} list 2>&1)"
echo "${LIST_OUT}" > "${SER}" 2>/dev/null
LIST_N="$(echo "${LIST_OUT}" | grep -oE 'PARTYOS-APP-LIST n=[0-9]+' | grep -oE '[0-9]+' | head -1)"
[ -n "${LIST_N}" ] || LIST_N=0
list_ok=0
if [ "${LIST_N}" -ge 1 ] && echo "${LIST_OUT}" | grep -qE "^${DUMMY}[[:space:]]"; then list_ok=1; fi
say "PARTYOS-APPSTORE-LIST-OK n=${LIST_N} dummy_in_list=${list_ok}"

# ============================ 2. install <dummy> (not-yet-local) ==============
say "PARTYOS-APPSTORE === install ${DUMMY} (not-yet-local -> download + mount) ==="
INST_OUT="$(${APP} install "${DUMMY}" 2>&1)"
echo "${INST_OUT}" > "${SER}" 2>/dev/null
dummy_miss=0;    echo "${INST_OUT}" | grep -qF "PARTYOS-APP-CACHE-MISS name=${DUMMY}" && dummy_miss=1
dummy_dl=0;      echo "${INST_OUT}" | grep -qF "PARTYOS-APP-DOWNLOADED name=${DUMMY}" && dummy_dl=1
dummy_inst=0;    echo "${INST_OUT}" | grep -qF "PARTYOS-APP-INSTALLED name=${DUMMY}" && mountpoint -q "/home/$(tr -d '[:space:]' </run/partyos-username 2>/dev/null || echo gamer)/games/${DUMMY}" 2>/dev/null && dummy_inst=1
say "PARTYOS-APPSTORE-DUMMY-INSTALL miss=${dummy_miss} downloaded=${dummy_dl} installed=${dummy_inst}"

# ============================ 3. launch <dummy> ==============================
say "PARTYOS-APPSTORE === launch ${DUMMY} ==="
LAUNCH_OUT="$(${APP} launch "${DUMMY}" 2>&1)"
echo "${LAUNCH_OUT}" > "${SER}" 2>/dev/null
dummy_run=0;     echo "${LAUNCH_OUT}" | grep -qF "${DUMMY_MARK}" && dummy_run=1

# ============================ 4. installed reflects state ====================
INSTALLED_AFTER="$(${APP} installed 2>&1)"
echo "${INSTALLED_AFTER}" > "${SER}" 2>/dev/null
ia_csv="$(echo "${INSTALLED_AFTER}" | grep -oE 'PARTYOS-APP-INSTALLED-LIST n=[0-9]+ apps=[^ ]*' | grep -oE 'apps=[^ ]*' | cut -d= -f2)"
say "PARTYOS-APPSTORE-INSTALLED-AFTER apps=${ia_csv}"
installed_has_dummy=0; echo ",${ia_csv}," | grep -qF ",${DUMMY}," && installed_has_dummy=1

# remove the dummy, confirm state drops it
REMOVE_OUT="$(${APP} remove "${DUMMY}" 2>&1)"
echo "${REMOVE_OUT}" > "${SER}" 2>/dev/null
removed=0;        echo "${REMOVE_OUT}" | grep -qF "PARTYOS-APP-REMOVED name=${DUMMY}" && removed=1
INSTALLED_AFTER_RM="$(${APP} installed 2>&1)"
iar_csv="$(echo "${INSTALLED_AFTER_RM}" | grep -oE 'apps=[^ ]*' | head -1 | cut -d= -f2)"
say "PARTYOS-APPSTORE-INSTALLED-AFTER-REMOVE apps=${iar_csv}"
removed_gone=0; echo ",${iar_csv}," | grep -qF ",${DUMMY}," || removed_gone=1
# the state assertion: dummy present after install, absent after remove.
state_ok=0; [ "${installed_has_dummy}" -eq 1 ] && [ "${removed}" -eq 1 ] && [ "${removed_gone}" -eq 1 ] && state_ok=1

# ============================ 5. one-click install-launch ====================
say "PARTYOS-APPSTORE === install-launch ${ONECLICK} (the GUI one-click path) ==="
OC_OUT="$(${APP} install-launch "${ONECLICK}" 2>&1)"
echo "${OC_OUT}" > "${SER}" 2>/dev/null
oc_run=0; echo "${OC_OUT}" | grep -qF "${ONECLICK_MARK}" && oc_run=1

# ============================ 6. launcher icons present =====================
# The per-app icons ARE the store (no window): gen-launchers drops a menu entry
# per catalog blob + a desktop launcher under a per-category subdir. Assert both.
${APP} gen-launchers >/dev/null 2>&1 || true
USER_NAME="$(tr -d '[:space:]' </run/partyos-username 2>/dev/null || echo gamer)"
[ -n "${USER_NAME}" ] || USER_NAME="gamer"
SHORTCUT_DIR="/home/${USER_NAME}/.local/share/applications"
shortcuts="$(ls -1 "${SHORTCUT_DIR}"/partyos-app-*.desktop 2>/dev/null | wc -l | tr -d ' ')"
desk_shortcuts="$(find "/home/${USER_NAME}/Desktop" -name 'partyos-app-*.desktop' 2>/dev/null | wc -l | tr -d ' ')"
store_desktop=0; [ "${desk_shortcuts}" -ge 1 ] && store_desktop=1
say "PARTYOS-APPSTORE-DESKTOP-OK desktop_icons=${desk_shortcuts} menu=${shortcuts}"

# ============================ verdict + callback =============================
ready=0
if [ "${list_ok}" -eq 1 ] && [ "${dummy_inst}" -eq 1 ] && [ "${dummy_run}" -eq 1 ] && \
   [ "${state_ok}" -eq 1 ] && [ "${oc_run}" -eq 1 ] && [ "${store_desktop}" -eq 1 ] && \
   [ "${shortcuts}" -ge 1 ]; then
    ready=1
    say "PARTYOS-APPSTORE-READY app-store backend + launcher verified"
    curl -s --max-time 5 \
      "${report_base}/report?step=appstore&status=ok&list=${LIST_N}&dummy_install=${dummy_inst}&dummy_run=${dummy_run}&dummy_marker=${DUMMY_MARK}&installed_after=${ia_csv}&removed=${removed}&oneclick_run=${oc_run}&store_desktop=${store_desktop}&shortcuts=${shortcuts}" \
      >/dev/null 2>&1 || say "PARTYOS-APPSTORE callback-failed (non-fatal)"
else
    say "PARTYOS-APPSTORE NOT ready (list_ok=${list_ok} dummy_inst=${dummy_inst} dummy_run=${dummy_run} state_ok=${state_ok} oneclick=${oc_run} store=${store_desktop} shortcuts=${shortcuts})"
    curl -s --max-time 5 \
      "${report_base}/report?step=appstore&status=fail&list=${LIST_N}&dummy_install=${dummy_inst}&dummy_run=${dummy_run}&state_ok=${state_ok}&oneclick_run=${oc_run}&store_desktop=${store_desktop}&shortcuts=${shortcuts}" \
      >/dev/null 2>&1 || true
fi

sync
umount "${MNT}" 2>/dev/null || mount -o remount,ro "${MNT}" 2>/dev/null || true

# --- heartbeats: prove the system stays up -----------------------------------
i=0
while [ "${i}" -lt 20 ]; do
    sleep 2; i=$((i+1))
    say "PARTYOS-APPSTORE-ALIVE heartbeat ${i} ready=${ready}"
    [ "${ready}" -eq 1 ] && [ "${i}" -ge 5 ] && break
done

say "PARTYOS-APPSTORE stay-up window complete, powering off"
sync
systemctl poweroff --no-block 2>/dev/null || poweroff -f 2>/dev/null || true
