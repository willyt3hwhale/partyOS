#!/usr/bin/env python3
"""
Simple HTTP server for serving partyOS boot files and resources.
Serves an allowlist of public files from the project root on the local network.

Adds a /report endpoint used as the autonomous "callback" channel: a booting
client (iPXE or the OS) fetches /report?step=N&status=ok&... ; the server logs a
single greppable line (REPORT step=N status=ok ...) and returns 200 so the
client does not treat the callback as an error. The VM test harness greps the
access log for these lines to assert progress with no human watching a screen.
"""

import http.server
import json
import os
import socketserver
import ssl
import sys
import threading
import time
from pathlib import Path
from urllib.parse import urlsplit, parse_qsl, unquote


# HTTPS leaf cert + key the server presents on the TLS port. Generated by
# scripts/deploy/gen-ca.sh (signed by the pinned partyOS CA). If absent the
# server runs HTTP-only with a warning, so it still works before gen-ca.sh is
# run.
TLS_DIR = Path(__file__).parent / "tls"
TLS_CERT = TLS_DIR / "partyos.crt"
TLS_KEY = TLS_DIR / "partyos.key"
# Default TLS port. HTTP keeps :8080 unchanged.
HTTPS_PORT = 8443


# Auto-hosted personal sites: an .html file in SITES_DIR is served at
# http://<server>/sites/<file>. _resolve_site_path keeps every request inside SITES_DIR.
# PARTYOS_SITES_DIR overrides SITES_DIR (default: server/sites/).
SITES_URL_PREFIX = "/sites"
SITES_DIR = Path(
    os.environ.get("PARTYOS_SITES_DIR") or (Path(__file__).parent / "sites")
).resolve()


# --- SECRET DENYLIST -------------------------------------------------------
# The docroot is the whole repo (directory=project_root), which also holds
# secrets: ca/, server/tls/, users/, server/reports/, deploy.conf and .git.
# _is_secret_path() returns 403 for these paths. It uses resolve-then-contains,
# so traversal, percent-encoding and symlink variants cannot bypass it.
# The public CA cert is pinned on the client and is never fetched, so denying
# all of ca/ breaks no boot path.
DOCROOT = Path(__file__).parent.parent.resolve()
# Directories whose entire subtree is secret (GET + listing denied). The /report
# and /feedback POST endpoints are routed BEFORE this guard, so denying reads
# under server/reports/ only blocks reading the inbox back out, not submitting.
SECRET_DIRS = ("ca", "server/tls", "users", "server/reports", ".git")
# Exact repo-root-relative files that are secret.
SECRET_FILES = ("deploy.conf",)
# Any file with one of these suffixes is key material and never public, wherever
# it sits in the tree (defence in depth for a stray key/cert-key).
SECRET_SUFFIXES = (".key", ".pem")


# --- PUBLIC ALLOWLIST ------------------------------------------------------
# The docroot is still the whole repo, but only the paths below are served. Every
# other path is a 404. The secret denylist above stays as a second layer and runs
# first (403). The list comes from the paths real clients fetch: the iPXE script and
# boot scripts, the kernel, initramfs and airootfs, the catalog, blobs, torrents and
# icons, the game config templates, the pacman LAN mirrors, the notices feed, the
# portal page and boot-config.sh. /report, /feedback and /sites have their own routes.
# Each entry is a path relative to the docroot. The check uses the lexical request
# path, so "..", "%2e%2e" and "//" spellings collapse before the match.
ALLOW_DIRS = (
    "boot",
    "portal",
    "server/images",
    "server/games",
    "server/config",
    "server/lanmirror",
    "server/lanmirror-local",
)
ALLOW_FILES = (
    "server/notices.json",
    "server/boot-config.sh",
)
# Names that are never served, also inside an allowed directory: backups (*.bak*),
# editor files (*~, *.swp), key material (*.key, *.pem) and dotfiles (this includes
# the macOS "._name" files). Templates (*.tmpl) are refused too, except under
# TMPL_OK_DIRS: partyos-launch and partyos-messenger-config fetch the game and
# HexChat templates from server/config/ and fill them in on the client.
DENY_NAME_SUFFIXES = ("~", ".swp", ".key", ".pem")
TMPL_OK_DIRS = ("server/config",)


def _bad_name(name):
    """True if `name` is a dotfile, a backup, an editor file or key material."""
    return name.startswith(".") or ".bak" in name or name.endswith(DENY_NAME_SUFFIXES)


def _name_denied(parts):
    """True if a path component of `parts` has a name that is never served."""
    if any(_bad_name(name) for name in parts):
        return True
    if parts and parts[-1].endswith(".tmpl"):
        for d in TMPL_OK_DIRS:
            dparts = tuple(d.split("/"))
            if tuple(parts[:len(dparts)]) == dparts:
                return False
        return True
    return False


def _under(parts, prefixes):
    """True if `parts` is one of `prefixes` or a path below one of them."""
    for d in prefixes:
        dparts = tuple(d.split("/"))
        if tuple(parts[:len(dparts)]) == dparts:
            return True
    return False


# Where in-session player reports land (one timestamped JSON file each), for the
# operator to triage after the event. Next to the script (server/reports/), NOT
# the project root - it's operator data, gitignored. Created on first report.
REPORTS_DIR = Path(__file__).parent / "reports"
# The server is threaded (one thread per request), so two clients can submit a
# report at the same instant. The filename carries a monotonic counter to keep
# concurrent reports from colliding on the same timestamp; the lock serializes
# the counter bump + mkdir so the unique-name guarantee holds across threads.
_reports_lock = threading.Lock()
_reports_seq = 0


def _persist_report(fields):
    """Write one player report as a timestamped JSON file under REPORTS_DIR.

    Returns the filename written. Single-process-safe: the lock serializes the
    sequence bump so concurrent submissions never share a name. Best-effort -
    callers treat a failed persist as a 500, never a crash.
    """
    global _reports_seq
    with _reports_lock:
        REPORTS_DIR.mkdir(parents=True, exist_ok=True)
        _reports_seq += 1
        seq = _reports_seq
        # Stamp the server-side receive time alongside whatever the client sent.
        fields = dict(fields)
        fields.setdefault("received_at", f"{time.time():.3f}")
        # Sortable name: ISO-ish UTC + a per-process counter for same-second ties.
        stamp = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())
        name = f"{stamp}-{seq:04d}.json"
        path = REPORTS_DIR / name
        with open(path, "w", encoding="utf-8") as f:
            json.dump(fields, f, ensure_ascii=False, indent=2, sort_keys=True)
            f.write("\n")
    return name


class PartyOSHTTPHandler(http.server.SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        # Serve from the project root, not just the server directory.
        project_root = str(Path(__file__).parent.parent)
        super().__init__(*args, directory=project_root, **kwargs)

    def _handle_report(self, parsed):
        # Flatten the query into a stable "k=v k=v" string for easy grepping.
        params = parse_qsl(parsed.query, keep_blank_values=True)
        kv = " ".join(f"{k}={v}" for k, v in params)
        # The REPORT line is the marker the harness greps in the access log.
        # Leading epoch timestamp lets the harness derive per-stage timings.
        print(f"[HTTP] {time.time():.3f} REPORT {kv}")
        body = b"ok\n"
        self.send_response(200)
        self.send_header("Content-Type", "text/plain")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        return body

    def _handle_feedback(self, fields):
        """Persist one in-session player inbox entry and return 200 with the filename.

        Separate from /report on purpose: /report is the fire-and-forget boot
        telemetry the harness greps (a log line, nothing on disk). /feedback is a
        durable, operator-reviewed artifact - a player pressing "Report an Issue".
        `fields` is a flat str->str dict (parsed from a POST body or GET query).

        The payload shape VARIES by opt-in: a plain message carries nick + message
        only; a bug report (is_bug=true) ALSO carries build_id + log_tail (+ game +
        mem_free). Persistence is schema-agnostic - it stores whatever fields arrive,
        so both shapes land as a clean, readable JSON inbox entry. Legacy
        partyos-report-1 reports (category/details/hostname/...) still persist too.
        """
        try:
            name = _persist_report(fields)
        except OSError as e:
            print(f"[HTTP] {time.time():.3f} FEEDBACK-ERROR {e}")
            body = b"feedback persist failed\n"
            self.send_response(500)
            self.send_header("Content-Type", "text/plain")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            return body
        # One greppable line (mirrors the REPORT marker) so the harness/operator can
        # see a report arrived without opening the file. New inbox shape keys on
        # nick + is_bug + a short message snippet; falls back to the legacy
        # category/details fields so old clients still log meaningfully.
        nick = fields.get("nick", "") or fields.get("hostname", "")
        bug = fields.get("is_bug", "")
        snippet = (fields.get("message", "") or fields.get("details", "")
                   or fields.get("category", "")).replace("\n", " ")[:60]
        print(f"[HTTP] {time.time():.3f} FEEDBACK saved={name} nick={nick} is_bug={bug} msg={snippet!r}")
        body = (f"saved {name}\n").encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "text/plain")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        return body

    def do_POST(self):
        # Only /feedback accepts POST; everything else 405s. The report body can be
        # urlencoded (k=v&...) or a JSON object; the client picks whichever is
        # simplest. Connection drops are normal (see do_GET) - swallow, don't trace.
        try:
            parsed = urlsplit(self.path)
            if parsed.path != "/feedback":
                self.send_error(405, "Method Not Allowed")
                return
            length = int(self.headers.get("Content-Length") or 0)
            # Bound the read so a runaway/oversized body can't exhaust memory.
            length = max(0, min(length, 1 * 1024 * 1024))
            raw = self.rfile.read(length) if length else b""
            ctype = (self.headers.get("Content-Type") or "").split(";")[0].strip().lower()
            fields = {}
            if ctype == "application/json":
                try:
                    obj = json.loads(raw.decode("utf-8") or "{}")
                    if isinstance(obj, dict):
                        # Coerce values to strings so persistence is uniform.
                        fields = {str(k): ("" if v is None else str(v)) for k, v in obj.items()}
                except (ValueError, UnicodeDecodeError):
                    fields = {}
            else:
                # Default: treat as urlencoded form (also covers GET-style bodies).
                fields = dict(parse_qsl(raw.decode("utf-8", "replace"), keep_blank_values=True))
            # Merge any query-string params too (client may split context across both).
            fields.update(dict(parse_qsl(parsed.query, keep_blank_values=True)))
            body = self._handle_feedback(fields)
            self.wfile.write(body)
        except (BrokenPipeError, ConnectionResetError):
            print(f"[XFER] {time.time():.3f} {self.address_string()} - client closed connection (feedback POST)")

    def do_GET(self):
        # A client cancelling a download (the app-store Cancel button, or aria2
        # switching to a peer mid-pull) drops the connection -> BrokenPipe/ConnReset.
        # That's normal, not an error; log one line instead of a full traceback.
        try:
            self._do_GET()
        except (BrokenPipeError, ConnectionResetError):
            print(f"[XFER] {time.time():.3f} {self.address_string()} - client closed connection (download cancelled)")

    def _do_GET(self):
        parsed = urlsplit(self.path)
        if parsed.path == "/report":
            body = self._handle_report(parsed)
            self.wfile.write(body)
            return
        # GET /feedback?... : a no-curl-POST fallback for the client. Same handler,
        # fields come from the query string. Keeps the client simple if POST is hard.
        if parsed.path == "/feedback":
            body = self._handle_feedback(dict(parse_qsl(parsed.query, keep_blank_values=True)))
            self.wfile.write(body)
            return
        # Personal sites: route before the generic repo-root serve, so the path
        # resolves only inside SITES_DIR.
        if self._is_site_path(parsed.path):
            self._serve_site(parsed)
            return
        # Secret denylist: the docroot is the WHOLE repo, so refuse any request that
        # maps to key material / player PII / configs / .git BEFORE the generic
        # repo-root serve - and before Range, so a `curl -r 0-0` probe can't leak
        # them either.
        if self._is_secret_path(self.path):
            print(f"[HTTP] {time.time():.3f} DENY secret request {self.path} "
                  f"from {self.address_string()}")
            self.send_error(403, "Forbidden")
            return
        # Allowlist: anything that is not a public artifact is a 404, before Range.
        if not self._is_public_path(self.path):
            self._deny_not_public("request")
            return
        # Honor HTTP Range so archiso's 1-byte existence probe
        # (`curl -r 0-0 airootfs.sfs`) gets 1 byte, not the whole 943M. Without
        # this the probe is served in full -> the sfs is transferred TWICE.
        if self.headers.get("Range") and self._serve_range():
            return
        super().do_GET()

    def _serve_range(self):
        """Serve a single `bytes=start-end` range as 206. True if handled."""
        rng = self.headers.get("Range", "")
        if not rng.startswith("bytes="):
            return False
        path = self.translate_path(self.path)
        if not os.path.isfile(path):
            return False  # let super().do_GET() emit the 404
        size = os.path.getsize(path)
        spec = rng[len("bytes="):].split(",")[0].strip()  # first range only
        try:
            s, _, e = spec.partition("-")
            if s == "":                       # suffix: bytes=-N
                start = max(0, size - int(e)); end = size - 1
            else:
                start = int(s); end = int(e) if e else size - 1
        except ValueError:
            return False
        if start >= size or start > end:
            self.send_response(416)
            self.send_header("Content-Range", f"bytes */{size}")
            self.end_headers()
            return True
        end = min(end, size - 1)
        nbytes = end - start + 1
        with open(path, "rb") as f:
            f.seek(start)
            self.send_response(206)
            self.send_header("Content-Type", self.guess_type(path))
            self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
            self.send_header("Content-Length", str(nbytes))
            self.send_header("Accept-Ranges", "bytes")
            self.end_headers()
            remaining = nbytes
            try:
                while remaining > 0:
                    buf = f.read(min(256 * 1024, remaining))
                    if not buf:
                        break
                    self.wfile.write(buf)
                    remaining -= len(buf)
            except (BrokenPipeError, ConnectionResetError):
                pass
        print(f"[XFER] {time.time():.3f} {self.path} RANGE {start}-{end} ({nbytes}B)")
        return True

    def copyfile(self, source, outputfile):
        # Instrumented: log bytes actually sent + duration per file GET, and flag
        # client-aborted transfers - to tell a real download from a size-probe.
        start = time.time()
        total = 0
        try:
            while True:
                buf = source.read(256 * 1024)
                if not buf:
                    break
                outputfile.write(buf)
                total += len(buf)
        except (BrokenPipeError, ConnectionResetError) as e:
            print(f"[XFER] {time.time():.3f} {self.path} ABORTED {total}B "
                  f"in {time.time()-start:.2f}s ({type(e).__name__})")
            raise
        print(f"[XFER] {time.time():.3f} {self.path} sent {total}B "
              f"in {time.time()-start:.2f}s")

    def _is_site_path(self, path):
        # Match the dedicated /sites docroot: exactly "/sites" or anything under
        # "/sites/". "/sitesX" or "/sites-foo" deliberately do NOT match (no prefix
        # confusion), so only this narrow route is diverted to the scoped handler.
        return path == SITES_URL_PREFIX or path.startswith(SITES_URL_PREFIX + "/")

    def _is_secret_path(self, path):
        """True if `path` maps to a secret file/dir under the docroot (=> 403).

        Resolves the request to the REAL filesystem path the base handler would
        serve - translate_path() already unquotes (so %2e%2e can't smuggle a `..`),
        strips the query and collapses `..`/`//` lexically onto the docroot - then
        .resolve() to also follow symlinks, and tests that RESOLVED path for
        containment in a SECRET_DIRS subtree, an exact SECRET_FILES match, or a
        key-material suffix. Because the test is on the resolved real path (not the
        raw URL), every traversal / percent-encoding / symlink / double-slash
        spelling of a secret (/ca/../ca/partyos-ca.key, /%2e%2e/ca/..., //ca/...)
        collapses to the same path and is caught. Fails CLOSED: an unresolvable path
        is treated as secret. A path resolving OUTSIDE the docroot is left to the
        base handler (which 404s it) so this guard never 403s unrelated content.
        """
        try:
            real = Path(self.translate_path(path)).resolve()
        except (ValueError, OSError):
            return True
        try:
            parts = real.relative_to(DOCROOT).parts
        except ValueError:
            return False
        if not parts:
            return False
        if real.suffix in SECRET_SUFFIXES:
            return True
        if "/".join(parts) in SECRET_FILES:
            return True
        for d in SECRET_DIRS:
            dparts = tuple(d.split("/"))
            if parts[:len(dparts)] == dparts:
                return True
        return False

    def _is_public_path(self, path):
        """True if `path` maps to a file in the public allowlist (else => 404).

        translate_path() unquotes the URL, drops the query and removes ".." and "."
        components, so the match is on the lexical path inside the docroot. The
        request must be one of ALLOW_FILES or lie below one of ALLOW_DIRS, and no
        component can have a denied name (see _name_denied). If the path resolves
        through a symlink, the real target must pass the same checks. A
        directory is public only if it holds an index.html: there are no listings.
        Fails closed: a path that does not resolve is not public.
        """
        translated = self.translate_path(path)
        rel = os.path.relpath(translated, self.directory)
        if rel == "." or rel == ".." or rel.startswith(".." + os.sep):
            return False
        parts = tuple(p for p in rel.split(os.sep) if p)
        if not parts or _name_denied(parts):
            return False
        if "/".join(parts) not in ALLOW_FILES and not _under(parts, ALLOW_DIRS):
            return False
        try:
            real = Path(translated).resolve()
        except (ValueError, OSError):
            return False
        if _bad_name(real.name):
            return False
        # A symlink inside an allowed directory must not lead back to a private
        # file in the repo. A target outside the docroot (external storage) is not
        # checked here; the secret denylist still applies to it.
        try:
            real_parts = real.relative_to(DOCROOT).parts
        except ValueError:
            real_parts = None
        if real_parts is not None and (
                _name_denied(real_parts)
                or ("/".join(real_parts) not in ALLOW_FILES
                    and not _under(real_parts, ALLOW_DIRS))):
            return False
        if os.path.isdir(translated):
            return os.path.isfile(os.path.join(translated, "index.html"))
        return True

    def _deny_not_public(self, kind):
        print(f"[HTTP] {time.time():.3f} DENY not-public {kind} {self.path} "
              f"from {self.address_string()}")
        self.send_error(404, "Not Found")

    def list_directory(self, path):
        # No directory listings anywhere. _is_public_path() already refuses a
        # directory with no index.html; this is the second layer.
        self.send_error(404, "Not Found")
        return None

    def _resolve_site_path(self, url_path):
        """Map a /sites/... URL to a real path STRICTLY inside SITES_DIR.

        Returns the resolved absolute Path when it lands on SITES_DIR or a
        descendant, else None (the caller then answers 403). The URL is unquoted
        FIRST (so %2e%2e can't smuggle a `..` past the check), never treated as
        absolute (leading slashes stripped), then fully resolved - which collapses
        `..` AND follows symlinks. The containment test is on the RESOLVED real path,
        so an escaping symlink or a `../` traversal both resolve outside SITES_DIR and
        are rejected. This is the one gate that keeps the route from ever reaching
        ca/, server/tls/, deploy.conf, users/, .git/ or any other repo path.
        """
        try:
            rel = unquote(url_path[len(SITES_URL_PREFIX):]).lstrip("/")
            candidate = (SITES_DIR / rel).resolve()
        except (ValueError, OSError):
            return None
        if candidate != SITES_DIR and SITES_DIR not in candidate.parents:
            return None
        return candidate

    def _serve_site(self, parsed, head=False):
        """Serve one guest personal-site request from SITES_DIR (scoped, additive).

        A directory serves its index.html if present, else a 404 (no listing); a file
        is streamed with its guessed content type. Anything that resolves outside
        SITES_DIR is a 403 - the route never widens exposure beyond the site dir.
        """
        target = self._resolve_site_path(parsed.path)
        if target is None:
            self.send_error(403, "Forbidden")
            return
        # Same name rules as the rest of the tree (no dotfiles, backups, keys).
        raw_parts = tuple(p for p in unquote(parsed.path).split("/") if p not in ("", ".", ".."))
        if _name_denied(raw_parts) or _name_denied(target.relative_to(SITES_DIR).parts):
            self.send_error(404, "Not Found")
            return
        if target.is_dir():
            # No directory listings: a directory is served only by its index.html.
            index = target / "index.html"
            if not index.is_file():
                self.send_error(404, "Not Found")
                return
            target = index
        if not target.is_file():
            self.send_error(404, "Not Found")
            return
        try:
            f = open(target, "rb")
        except OSError:
            self.send_error(404, "Not Found")
            return
        try:
            st = os.fstat(f.fileno())
            self.send_response(200)
            self.send_header("Content-Type", self.guess_type(str(target)))
            self.send_header("Content-Length", str(st.st_size))
            self.end_headers()
            if not head:
                self.copyfile(f, self.wfile)
        finally:
            f.close()

    def do_HEAD(self):
        parsed = urlsplit(self.path)
        if parsed.path == "/report":
            self._handle_report(parsed)
            return
        if self._is_site_path(parsed.path):
            self._serve_site(parsed, head=True)
            return
        # Same secret denylist as _do_GET: a HEAD must not leak existence/size of a
        # key/PII/config either.
        if self._is_secret_path(self.path):
            print(f"[HTTP] {time.time():.3f} DENY secret HEAD {self.path} "
                  f"from {self.address_string()}")
            self.send_error(403, "Forbidden")
            return
        if not self._is_public_path(self.path):
            self._deny_not_public("HEAD")
            return
        super().do_HEAD()

    def _log_tag(self):
        # Per-request log prefix that self-identifies the listener this request
        # came in on: [HTTP:8080] for the plaintext listener, [HTTPS:8443] for
        # the TLS one. Read off the server instance (tagged in _make_httpd /
        # _serve_https) so the same handler class serves both transports yet each
        # line says which port+scheme it arrived on - verifying the HTTPS boot
        # chain from the log alone, no live lsof watcher. Falls back to [HTTP] if
        # an instance was created without the tag (defensive).
        scheme = getattr(self.server, "partyos_scheme", "HTTP")
        port = getattr(self.server, "partyos_port", None)
        return f"[{scheme}:{port}]" if port is not None else f"[{scheme}]"

    def log_message(self, fmt, *args):
        # Epoch timestamp (seconds.millis) prefixes each line so the harness can
        # compute transfer windows: a file's download time ~= this request's
        # completion timestamp minus the previous request's. The tag distinguishes
        # the HTTP:8080 vs HTTPS:8443 listener; ip/timestamp/request-line otherwise
        # identical to before.
        print(f"{self._log_tag()} {time.time():.3f} {self.address_string()} - {fmt % args}")


class ThreadingTCPServer(socketserver.ThreadingMixIn, socketserver.TCPServer):
    """Threaded server: each request gets its own thread, so one client pulling a
    multi-GB blob does NOT block every other client (catalog fetches, other blob
    downloads). The single-threaded TCPServer serialized everything - fine for one
    test client, fatal at a LAN party where many clients download at once.
    daemon_threads so a Ctrl-C exits cleanly without waiting on in-flight transfers."""
    daemon_threads = True
    allow_reuse_address = True

    # Apply TLS PER-CONNECTION here, not by wrapping the LISTENING socket. When
    # the listening socket is wrapped, accept() performs the whole handshake on the
    # single accept thread BEFORE ThreadingMixIn forks a worker, with no timeout - so
    # one client that connects but never completes the handshake wedges accept()
    # forever and no other client can boot. Instead we accept the raw connection and,
    # for a TLS listener, wrap the accepted socket with a bounded handshake timeout:
    # a stalled handshake is dropped (get_request raises OSError, which serve_forever
    # swallows and moves on) instead of freezing the loop. partyos_tls_ctx is None for
    # a plaintext listener (get_request then behaves exactly as before).
    partyos_tls_ctx = None
    partyos_handshake_timeout = 10

    def get_request(self):
        conn, addr = super().get_request()
        if self.partyos_tls_ctx is not None:
            # Bound the handshake so a stalled client is dropped, not serviced forever.
            conn.settimeout(self.partyos_handshake_timeout)
            try:
                conn = self.partyos_tls_ctx.wrap_socket(conn, server_side=True)
            except OSError:
                # Failed/stalled/timed-out handshake: close and re-raise so the accept
                # loop drops this connection and keeps serving everyone else.
                try:
                    conn.close()
                except OSError:
                    pass
                raise
            # Handshake done: clear the short deadline so a legitimate slow/large
            # transfer (a multi-GB blob) is not killed by the handshake timeout.
            conn.settimeout(None)
        return conn, addr


def _make_tls_context():
    """Build the SSLContext the HTTPS listener wraps its sockets with, or None.

    Returns a configured ssl.SSLContext when the leaf cert+key from gen-ca.sh are
    present and loadable, else None (the caller then runs HTTP-only). Never
    raises for a missing/bad cert - a TLS misconfig must not take down the
    plaintext boot chain. PROTOCOL_TLS_SERVER negotiates the best modern TLS;
    we only load our own leaf chain - clients pin our CA, we don't verify them.
    """
    if not (TLS_CERT.exists() and TLS_KEY.exists()):
        print(f"[HTTPS] cert/key not found ({TLS_CERT}, {TLS_KEY}) - "
              f"running HTTP-only. Run scripts/deploy/gen-ca.sh to enable HTTPS.")
        return None
    try:
        ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        ctx.load_cert_chain(certfile=str(TLS_CERT), keyfile=str(TLS_KEY))
        return ctx
    except (ssl.SSLError, OSError) as e:
        print(f"[HTTPS] failed to load cert chain ({TLS_CERT}): {e} - "
              f"running HTTP-only.")
        return None


def _make_httpd(port, bind, scheme="HTTP"):
    """Create (but do not serve) one ThreadingTCPServer on bind:port.

    Tags the instance with its bound port + scheme so the handler's per-request
    log line can self-identify the listener ([HTTP:8080] vs [HTTPS:8443]) - both
    listeners share one handler class, the tag is the only thing that differs.
    The TLS listener passes scheme="HTTPS"; the default keeps plaintext as HTTP.
    """
    httpd = ThreadingTCPServer((bind, port), PartyOSHTTPHandler)
    httpd.partyos_scheme = scheme
    httpd.partyos_port = port
    return httpd


def _serve_https(ctx, port, bind):
    """Serve forever over TLS on bind:port, wrapping accepted sockets with ctx.

    Returns True if the listener BOUND (and served until shutdown), False if the
    bind FAILED. The caller decides fatality: in HTTPS-only mode a False return is
    fatal (start_server exits non-zero rather than leaving zero listeners); in
    dual-serve it is non-fatal (the plaintext HTTP listener still serves - HTTPS is
    additive). A bind failure is logged to stderr with the addr:port.

    Runs in its own thread alongside the plaintext listener in dual-serve. The
    SAME handler (PartyOSHTTPHandler) serves both - Range support, /report,
    /feedback and all logging are identical; only the transport differs.
    """
    try:
        httpd = _make_httpd(port, bind, scheme="HTTPS")
    except OSError as e:
        print(f"[HTTPS] could not bind {bind or '0.0.0.0'}:{port}: {e}",
              file=sys.stderr)
        return False
    # Wrap accepted connections (NOT the listening socket) with this ctx: get_request
    # does the per-connection wrap under a bounded handshake timeout (see get_request above), so
    # a stalled handshake can never block the accept loop for the whole party.
    httpd.partyos_tls_ctx = ctx
    where = bind if bind else "0.0.0.0 (all interfaces)"
    print(f"partyOS HTTPS server running on {where}:{port}")
    print(f"Access at: https://localhost:{port} (pin ca/partyos-ca.crt)")
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        pass
    return True


def _serve_http_foreground(port, bind):
    """Serve plaintext HTTP on bind:port in the FOREGROUND (blocking).

    Shared by both modes: dual-serve runs this as the blocking call after the
    HTTPS thread is started; HTTPS-only never calls it (unless the cert is
    missing and the fallback runs).
    """
    try:
        with _make_httpd(port, bind) as httpd:
            project_root = Path(__file__).parent.parent
            where = bind if bind else "0.0.0.0 (all interfaces)"
            print(f"partyOS HTTP server running on {where}:{port}")
            print(f"Serving files from: {project_root}")
            print(f"Access at: http://localhost:{port}")
            httpd.serve_forever()
    except KeyboardInterrupt:
        print("\nServer stopped.")
    except OSError as e:
        where = bind if bind else "0.0.0.0"
        print(f"[HTTP] FATAL: could not bind {where}:{port}: {e}", file=sys.stderr)
        sys.exit(1)


def start_server(port=8080, bind="", https_port=HTTPS_PORT, enable_https=True,
                 enable_http=True):
    """Start the plaintext HTTP server (and, if certs exist, an HTTPS listener).

    bind="" (the default) binds all interfaces, exactly as before. Passing a
    bind IP pins the listener to one address - used by the server split so the
    netboot role and each blob role can run as independent processes on their own
    IPs (or the same host, different ports). Omit it for the single-box all-roles
    server and behaviour is unchanged.

    Dual-serve (enable_http True, the python-level default): when
    enable_https and the gen-ca.sh leaf cert+key exist, an HTTPS listener on
    https_port is started in a daemon thread BEFORE the blocking HTTP
    serve_forever. The HTTP listener on `port` is UNCHANGED whether or not HTTPS
    comes up - so missing certs degrade to HTTP-only, never a crash.

    HTTPS-only (enable_http False, set via PARTYOS_HTTP_DISABLE): the plaintext
    :port listener is NOT bound; HTTPS runs in the FOREGROUND so the process
    blocks and keeps serving TLS only. If there are no certs (ctx is None), it logs
    a warning and serves HTTP. (run-servers.sh makes HTTPS-only the prod default.)
    """
    # Bring up HTTPS first (in a background thread) so both transports share this
    # process and a Ctrl-C stops both. A missing/bad cert -> ctx is None -> HTTP
    # only, with the warning already logged.
    ctx = _make_tls_context() if enable_https else None

    if not enable_http:
        # HTTPS-only: run HTTPS in the foreground (blocking) so the process stays
        # alive serving TLS. If certs are absent there is nothing to serve over
        # TLS - fall back to HTTP so the box never ends up with zero listeners.
        if ctx is not None:
            # A bind failure here is FATAL: HTTPS-only means the TLS listener is
            # the ONLY listener, so if it cannot bind we must NOT exit 0 leaving
            # zero listeners. A stale process would keep serving OLD artifacts while we falsely
            # "succeed". Exit non-zero + loud so run-servers.sh notices + respawns.
            if not _serve_https(ctx, https_port, bind):
                where = bind if bind else "0.0.0.0"
                print(f"[HTTPS] FATAL: HTTPS-only mode but the TLS listener could "
                      f"not bind {where}:{https_port} - refusing to exit 0 with "
                      f"zero listeners (is another process already on :{https_port}?)",
                      file=sys.stderr)
                sys.exit(1)
            return
        print("[HTTPS] HTTPS-only was requested (PARTYOS_HTTP_DISABLE) but no "
              "certs are present - falling back to serving HTTP so the box is "
              "not left with zero listeners. Run gen-ca.sh to enable HTTPS.")
        _serve_http_foreground(port, bind)
        return

    # Dual-serve: HTTPS in a background thread, blocking HTTP serve in foreground.
    if ctx is not None:
        t = threading.Thread(
            target=_serve_https, args=(ctx, https_port, bind), daemon=True)
        t.start()
    _serve_http_foreground(port, bind)


if __name__ == "__main__":
    # argv[1] = port (as before); argv[2] = optional bind IP (default "" = all);
    # argv[3] = optional HTTPS port (default 8443). HTTPS is enabled automatically
    # when the gen-ca.sh leaf cert+key are present; set PARTYOS_NO_HTTPS=1 to
    # force HTTP-only regardless. Set PARTYOS_HTTP_DISABLE=1 to drop the plaintext
    # :PORT listener and serve HTTPS-ONLY (the python-level default keeps HTTP ON
    # for backward compat; run-servers.sh flips the PROD default to HTTPS-only).
    if len(sys.argv) > 1 and sys.argv[1] in ("-h", "--help"):
        print("Usage: http_server.py [PORT] [BIND_IP] [HTTPS_PORT]")
        print("  PORT        plaintext listen port (default 8080)")
        print("  BIND_IP     address to bind (default all interfaces)")
        print(f"  HTTPS_PORT  TLS listen port (default {HTTPS_PORT}); needs")
        print("              server/tls/partyos.{crt,key} from gen-ca.sh")
        print("  env PARTYOS_NO_HTTPS=1      disable the HTTPS listener entirely")
        print("  env PARTYOS_HTTP_DISABLE=1  disable the plaintext HTTP listener")
        print("                              (HTTPS-ONLY; falls back to HTTP if no certs)")
        sys.exit(0)
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 8080
    bind = sys.argv[2] if len(sys.argv) > 2 else ""
    https_port = int(sys.argv[3]) if len(sys.argv) > 3 else HTTPS_PORT
    enable_https = os.environ.get("PARTYOS_NO_HTTPS", "") not in ("1", "true", "yes")
    enable_http = os.environ.get("PARTYOS_HTTP_DISABLE", "") not in ("1", "true", "yes")
    start_server(port, bind, https_port=https_port, enable_https=enable_https,
                 enable_http=enable_http)
